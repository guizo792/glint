let language = "en";

export function setLanguage(next: string) {
  language = next;
}

export function t(key: Key, values: Record<string, string | number> = {}): string {
  const text = (language === "fr" && fr[key]) || en[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
